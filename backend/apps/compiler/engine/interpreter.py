"""
Runtime Interpreter for WRH-Lang.
Executes the AST generated by the parser and verified by the semantic analyzer.
Captures output from flex() print statements and enforces loop iteration safety.
"""

from typing import Any, Dict, List, Optional, Tuple


class RuntimeError(Exception):
    def __init__(self, message: str, line: int = 1):
        super().__init__(message)
        self.message = message
        self.line = line


class Interpreter:
    """
    AST Walker that evaluates statements and expressions in memory.
    """

    def __init__(self, max_iterations: int = 50000):
        self.env: Dict[str, Any] = {}
        self.output: List[str] = []
        self.max_iterations = max_iterations

    def run(self, stmts: List[Any]) -> Tuple[List[str], Optional[str]]:
        """
        Executes list of statements.
        Returns (output_lines, runtime_error_message).
        """
        try:
            self.execute_block(stmts)
            return self.output, None
        except RuntimeError as e:
            err_msg = f"Runtime Error at line {e.line}: {e.message}"
            self.output.append(err_msg)
            return self.output, err_msg
        except Exception as e:
            err_msg = f"Runtime Error: {str(e)}"
            self.output.append(err_msg)
            return self.output, err_msg

    def execute_block(self, stmts: List[Any]) -> None:
        for s in stmts:
            self.execute_stmt(s)

    def execute_stmt(self, s: Any) -> None:
        tag = s[0]

        # 1. Declaration: ('decl', var_type, name, init, line)
        if tag == "decl":
            _, var_type, name, init, line = s
            if init is not None:
                val = self.eval_expr(init)
            else:
                if var_type == "digit":
                    val = 0
                elif var_type == "verify":
                    val = False
                elif var_type == "textbody":
                    val = ""
                else:
                    val = None
            self.env[name] = val

        # 2. Assignment: ('assign', name, value_expr, line)
        elif tag == "assign":
            _, name, value_expr, line = s
            val = self.eval_expr(value_expr)
            self.env[name] = val

        # 3. If Statement: ('if', cond, then_block, else_block, line)
        elif tag == "if":
            _, cond, then_block, else_block, line = s
            cond_val = self.eval_expr(cond)
            if bool(cond_val):
                self.execute_block(then_block)
            elif else_block is not None:
                self.execute_block(else_block)

        # 4. While Statement: ('while', cond, body, line)
        elif tag == "while":
            _, cond, body, line = s
            iterations = 0
            while bool(self.eval_expr(cond)):
                iterations += 1
                if iterations > self.max_iterations:
                    raise RuntimeError(
                        f"execution exceeded loop safety limit ({self.max_iterations} iterations)",
                        line=line,
                    )
                self.execute_block(body)

        # 5. Print Statement: ('print', expr, line)
        elif tag == "print":
            _, expr, line = s
            val = self.eval_expr(expr)
            if isinstance(val, bool):
                out_str = "yes" if val else "no"
            elif val is None:
                out_str = "none"
            else:
                out_str = str(val)
            self.output.append(out_str)

    def eval_expr(self, e: Any) -> Any:
        tag = e[0]

        if tag == "num":
            return int(e[1])

        if tag == "str":
            raw = str(e[1])
            if raw.startswith('"') and raw.endswith('"'):
                return raw[1:-1]
            return raw

        if tag == "bool":
            return e[1] == "yes"

        if tag == "id":
            name, line = e[1], e[2]
            if name not in self.env:
                raise RuntimeError(f"variable '{name}' used before assignment", line=line)
            return self.env[name]

        if tag == "binop":
            _, op, left, right, line = e
            l = self.eval_expr(left)
            r = self.eval_expr(right)

            if op == "+++":
                return l + r
            elif op == "---":
                return l - r
            elif op == "**":
                return l * r
            elif op == "//":
                if r == 0:
                    raise RuntimeError("division by zero", line=line)
                return l // r
            elif op == ">>":
                return l > r
            elif op == "<<":
                return l < r
            elif op == "?=":
                return l == r
            elif op == "~":
                return l != r
            else:
                raise RuntimeError(f"unsupported operator '{op}'", line=line)

        raise RuntimeError(f"unrecognized expression: {tag}")


def interpret(stmts: List[Any]) -> Tuple[List[str], Optional[str]]:
    """Helper entry point to execute statements."""
    interp = Interpreter()
    return interp.run(stmts)
